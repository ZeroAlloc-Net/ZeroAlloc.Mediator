using System;
using System.Linq;
using Microsoft.Extensions.DependencyInjection;
using ZeroAlloc.Authorization;
using ZeroAlloc.Mediator;

namespace ZeroAlloc.Mediator.Authorization;

/// <summary>
/// Hooks the authorization pipeline into <see cref="IMediatorBuilder"/>. The configure
/// callback MUST select a security-context source — see <see cref="AuthorizationOptions"/>.
/// </summary>
public static class MediatorAuthorizationServiceCollectionExtensions
{
    public static IMediatorBuilder WithAuthorization(
        this IMediatorBuilder builder,
        Action<AuthorizationOptions>? configure = null)
    {
        ArgumentNullException.ThrowIfNull(builder);
        var services = builder.Services;
        var opts = new AuthorizationOptions(services);
        configure?.Invoke(opts);
        if (!opts.ContextSourceConfigured)
        {
            throw new InvalidOperationException(
                "WithAuthorization() requires a security-context source. Call ONE of: " +
                "UseSecurityContextFactory(sp => ...), UseAnonymousSecurityContext(), or " +
                "UseAccessor<TAccessor>() inside the configure callback.");
        }

        // D3 guard: ensure services.AddZeroAllocAuthorization() was called first. The bundled
        // generator in ZeroAlloc.Authorization registers ZeroAllocAuthorizationMarker on every call,
        // whether or not anything is decorated. AuthorizerFor<TRequest> is no signal: it is only
        // registered for [RequirePolicy] types, so a correct app without one would be refused.
        // Without the call, the behavior would silently fail-open on every request.
        if (!services.Any(sd => sd.ServiceType == typeof(ZeroAllocAuthorizationMarker)))
        {
            throw new InvalidOperationException(
                "WithAuthorization() requires services.AddZeroAllocAuthorization() to be called first. " +
                "Add 'services.AddZeroAllocAuthorization();' before 'services.AddMediator(...)' in Program.cs. " +
                "This call is generated by the ZeroAlloc.Authorization source generator and registers your " +
                "[Policy]-decorated classes plus the AuthorizerFor<TRequest> dispatchers as scoped services.");
        }

        // Idempotency guard: WithAuthorization may be called more than once safely.
        if (services.Any(d => d.ServiceType == typeof(AuthorizationBehaviorAccessor)))
            return builder;

        // Requests dispatched through IMediator are authorized against the dispatching
        // IMediator's own provider, the request's scope. This hands the container to the
        // behavior for requests dispatched without IMediator, which get a scope of their own on
        // it. The first IMediator resolved from the container constructs the accessor through
        // PipelineBehaviorStateActivation; resolving the accessor directly still works too.
        services.AddSingleton(sp => new AuthorizationBehaviorAccessor(sp));
        services.AddSingleton<IPipelineBehaviorStateInitializer>(sp => sp.GetRequiredService<AuthorizationBehaviorAccessor>());

        return builder;
    }
}
